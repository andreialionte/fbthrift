namespace FbThrift.Core.Compiler;

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

/// <summary>
/// C# code generator for Thrift IDL.
/// </summary>
public sealed class CSharpCodeGenerator
{
    private readonly ThriftCompilerOptions _options;
    private readonly StringBuilder _output = new();
    private int _indentLevel = 0;
    
    public CSharpCodeGenerator(ThriftCompilerOptions options)
    {
        _options = options ?? new ThriftCompilerOptions();
    }
    
    public string Generate(ThriftModule module)
    {
        _output.Clear();
        _indentLevel = 0;
        
        WriteHeader(module);
        WriteNamespaceStart(module);
        
        // Generate enums
        foreach (var enumType in module.Enums)
        {
            GenerateEnum(enumType);
        }
        
        // Generate structs
        foreach (var structType in module.Structs)
        {
            GenerateStruct(structType);
        }
        
        // Generate exceptions
        foreach (var exception in module.Exceptions)
        {
            GenerateException(exception);
        }
        
        // Generate unions
        foreach (var union in module.Unions)
        {
            GenerateUnion(union);
        }
        
        // Generate typedefs
        foreach (var typedef in module.Typedefs)
        {
            GenerateTypedef(typedef);
        }
        
        // Generate constants
        foreach (var constant in module.Constants)
        {
            GenerateConstant(constant);
        }
        
        // Generate services
        foreach (var service in module.Services)
        {
            GenerateService(service);
        }
        
        WriteNamespaceEnd();
        
        return _output.ToString();
    }
    
    private void WriteHeader(ThriftModule module)
    {
        _output.AppendLine("// <auto-generated />");
        _output.AppendLine($"// Generated from Thrift IDL: {module.Name}.thrift");
        _output.AppendLine($"// Generator: FbThrift C# Code Generator");
        _output.AppendLine();
        
        if (_options.EnableNullableReferenceTypes)
        {
            _output.AppendLine("#nullable enable");
            _output.AppendLine();
        }
        
        _output.AppendLine("using System;");
        _output.AppendLine("using System.Collections.Generic;");
        _output.AppendLine("using System.Collections.Immutable;");
        _output.AppendLine("using System.Threading.Tasks;");
        _output.AppendLine("using FbThrift.Core.Protocol;");
        _output.AppendLine("using FbThrift.Core.Rocket;");
        _output.AppendLine();
    }
    
    private void WriteNamespaceStart(ThriftModule module)
    {
        _output.AppendLine($"namespace {module.Namespace};");
        _output.AppendLine();
    }
    
    private void WriteNamespaceEnd()
    {
        _output.AppendLine("}");
    }
    
    private void WriteIndent()
    {
        for (int i = 0; i < _indentLevel; i++)
        {
            _output.Append(_options.IndentString);
        }
    }
    
    private void WriteLine(string line = "")
    {
        WriteIndent();
        _output.AppendLine(line);
    }
    
    private void IncreaseIndent() => _indentLevel++;
    private void DecreaseIndent() => _indentLevel--;
    
    private void GenerateEnum(ThriftEnum enumType)
    {
        WriteDocComment($"Enum {enumType.Name}");
        
        if (_options.GenerateDocComments)
        {
            WriteLine($"/// <summary>Thrift enum: {enumType.Name}</summary>");
        }
        
        WriteLine($"public enum {enumType.CSharpName} : int");
        WriteLine("{");
        IncreaseIndent();
        
        foreach (var value in enumType.Values)
        {
            if (_options.GenerateDocComments)
            {
                WriteLine($"/// <summary>Value: {value.Value}</summary>");
            }
            WriteLine($"{value.Name} = {value.Value},");
        }
        
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
    }
    
    private void GenerateStruct(ThriftStruct structType)
    {
        WriteDocComment($"Struct {structType.Name}");
        
        if (_options.GenerateDocComments)
        {
            WriteLine($"/// <summary>Thrift struct: {structType.Name}</summary>");
        }
        
        WriteLine($"public partial class {structType.CSharpName}");
        WriteLine("{");
        IncreaseIndent();
        
        // Fields
        foreach (var field in structType.Fields)
        {
            WriteField(field);
        }
        
        // Constructor
        GenerateStructConstructor(structType);
        
        // Serialization methods
        GenerateSerializationMethods(structType);
        
        // Equality
        GenerateEqualityMethods(structType);
        
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
    }
    
    private void GenerateException(ThriftException exception)
    {
        WriteDocComment($"Exception {exception.Name}");
        
        if (_options.GenerateDocComments)
        {
            WriteLine($"/// <summary>Thrift exception: {exception.Name}</summary>");
        }
        
        WriteLine($"public partial class {exception.CSharpName} : Exception");
        WriteLine("{");
        IncreaseIndent();
        
        foreach (var field in exception.Fields)
        {
            WriteField(field);
        }
        
        WriteLine($"public {exception.CSharpName}() : base() {{ }}");
        WriteLine($"public {exception.CSharpName}(string message) : base(message) {{ }}");
        WriteLine($"public {exception.CSharpName}(string message, Exception inner) : base(message, inner) {{ }}");
        
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
    }
    
    private void GenerateUnion(ThriftUnion union)
    {
        WriteDocComment($"Union {union.Name}");
        
        if (_options.GenerateDocComments)
        {
            WriteLine($"/// <summary>Thrift union: {union.Name}</summary>");
        }
        
        WriteLine($"public partial class {union.CSharpName}");
        WriteLine("{");
        IncreaseIndent();
        
        // Union fields are mutually exclusive
        foreach (var field in union.Fields)
        {
            WriteField(field);
        }
        
        // Type discriminator
        WriteLine($"public string ActiveField {{ get; private set; }} = string.Empty;");
        _output.AppendLine();
        
        // Factory methods for each field
        foreach (var field in union.Fields)
        {
            GenerateUnionFactoryMethod(union, field);
        }
        
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
    }
    
    private void GenerateUnionFactoryMethod(ThriftUnion union, ThriftField field)
    {
        WriteLine($"public static {union.CSharpName} Create{field.CSharpName}({field.Type.CSharpName} value)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"var result = new {union.CSharpName} {{");
        IncreaseIndent();
        WriteLine($"{field.CSharpName} = value,");
        WriteLine($"ActiveField = \"{field.Name}\"");
        DecreaseIndent();
        WriteLine("};");
        WriteLine("return result;");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
    }
    
    private void GenerateTypedef(ThriftTypedef typedef)
    {
        if (_options.GenerateDocComments)
        {
            WriteLine($"/// <summary>Typedef: {typedef.Name} = {typedef.Type.ThriftName}</summary>");
        }
        
        WriteLine($"using {typedef.CSharpName} = {typedef.Type.CSharpName};");
        _output.AppendLine();
    }
    
    private void GenerateConstant(ThriftConst constant)
    {
        if (_options.GenerateDocComments)
        {
            WriteLine($"/// <summary>Constant: {constant.Name} = {constant.Value}</summary>");
        }
        
        WriteLine($"public const {constant.Type.CSharpName} {constant.CSharpName} = {FormatConstantValue(constant.Value)};");
        _output.AppendLine();
    }
    
    private void GenerateService(ThriftService service)
    {
        if (_options.GenerateDocComments)
        {
            WriteLine($"/// <summary>Thrift service: {service.Name}</summary>");
        }
        
        // Check if service extends fb303.BaseService
        var extendsFb303 = service.Extends != null 
            && service.Extends.Name == "BaseService" 
            && service.Extends.Namespace == "fb303";
        
        // Generate interface
        if (extendsFb303)
        {
            WriteLine($"public interface I{service.CSharpName} : IFb303BaseService");
        }
        else
        {
            WriteLine($"public interface I{service.CSharpName}");
        }
        WriteLine("{");
        IncreaseIndent();
        
        foreach (var function in service.Functions)
        {
            GenerateFunctionSignature(function);
        }
        
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
        
        if (_options.GenerateServer)
        {
            GenerateServiceImplementation(service);
        }
        
        if (_options.GenerateAsync)
        {
            GenerateClient(service);
        }
    }
    
    private void GenerateFunctionSignature(ThriftFunction function)
    {
        string returnType = function.ReturnType.CSharpName;
        if (function.IsAsync && returnType != "void")
        {
            returnType = $"Task<{returnType}>";
        }
        else if (function.IsAsync && returnType == "void")
        {
            returnType = "Task";
        }
        
        if (_options.GenerateDocComments)
        {
            WriteLine($"/// <summary>Method: {function.Name}</summary>");
        }
        
        var paramsList = string.Join(", ", function.Parameters.Select(p => 
            $"{p.Type.CSharpName} {p.CSharpName}"));
        
        WriteLine($"{returnType} {function.CSharpName}({paramsList}, CancellationToken cancellationToken = default);");
    }
    
    private void GenerateClient(ThriftService service)
    {
        var extendsFb303 = service.Extends != null 
            && service.Extends.Name == "BaseService" 
            && service.Extends.Namespace == "fb303";
        
        var baseInterface = extendsFb303 ? $"I{service.CSharpName}, IFb303BaseService" : $"I{service.CSharpName}";
        
        WriteLine($"public sealed class {service.CSharpName}Client : {baseInterface}");
        WriteLine("{");
        IncreaseIndent();
        
        WriteLine($"private readonly IRocketClient _client;");
        _output.AppendLine();
        WriteLine($"public {service.CSharpName}Client(IRocketClient client)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine("_client = client ?? throw new ArgumentNullException(nameof(client));");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
        
        foreach (var function in service.Functions)
        {
            GenerateClientMethod(function);
        }
        
        // Add fb303 methods if service extends fb303.BaseService
        if (extendsFb303)
        {
            GenerateFb303ClientMethods();
        }
        
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
    }
    
    /// <summary>
    /// Generates fb303.BaseService methods in the client.
    /// </summary>
    private void GenerateFb303ClientMethods()
    {
        _output.AppendLine();
        WriteLine($"/// <summary>fb303.BaseService methods</summary>");
        WriteLine($"public async Task<string> GetNameAsync(CancellationToken cancellationToken = default)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"return await _client.SendRequestResponseAsync<string>(new GetNameRequest(), timeout, cancellationToken).ConfigureAwait(false);");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
        
        WriteLine($"public async Task<string> GetVersionAsync(CancellationToken cancellationToken = default)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"return await _client.SendRequestResponseAsync<string>(new GetVersionRequest(), timeout, cancellationToken).ConfigureAwait(false);");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
        
        WriteLine($"public async Task<ServiceStatus> GetStatusAsync(CancellationToken cancellationToken = default)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"return await _client.SendRequestResponseAsync<ServiceStatus>(new GetStatusRequest(), timeout, cancellationToken).ConfigureAwait(false);");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
        
        WriteLine($"public async Task<string> GetStatusDetailsAsync(CancellationToken cancellationToken = default)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"return await _client.SendRequestResponseAsync<string>(new GetStatusDetailsRequest(), timeout, cancellationToken).ConfigureAwait(false);");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
        
        WriteLine($"public async Task<Dictionary<string, string>> GetCountersAsync(CancellationToken cancellationToken = default)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"return await _client.SendRequestResponseAsync<Dictionary<string, string>>(new GetCountersRequest(), timeout, cancellationToken).ConfigureAwait(false);");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
        
        WriteLine($"public async Task<Dictionary<string, string>> GetDynamicCountersAsync(CancellationToken cancellationToken = default)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"return await _client.SendRequestResponseAsync<Dictionary<string, string>>(new GetDynamicCountersRequest(), timeout, cancellationToken).ConfigureAwait(false);");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
        
        WriteLine($"public async Task ReinitializeAsync(CancellationToken cancellationToken = default)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"await _client.SendRequestResponseAsync<ReinitializeResponse>(new ReinitializeRequest(), timeout, cancellationToken).ConfigureAwait(false);");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
    }
    
    private void GenerateClientMethod(ThriftFunction function)
    {
        string returnType = function.ReturnType.CSharpName;
        if (function.IsAsync && returnType != "void")
        {
            returnType = $"Task<{returnType}>";
        }
        else if (function.IsAsync && returnType == "void")
        {
            returnType = "Task";
        }
        
        var paramsList = string.Join(", ", function.Parameters.Select(p => 
            $"{p.Type.CSharpName} {p.CSharpName}"));
        
        WriteLine($"public async {returnType} {function.CSharpName}({paramsList}, CancellationToken cancellationToken = default)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"var request = new {function.CSharpName}Request {{");
        IncreaseIndent();
        foreach (var param in function.Parameters)
        {
            WriteLine($"{param.CSharpName} = {param.CSharpName},");
        }
        DecreaseIndent();
        WriteLine("};");
        _output.AppendLine();
        WriteLine($"var response = await _client.SendRequestResponseAsync<{function.ReturnType.CSharpName}>(");
        IncreaseIndent();
        WriteLine($"new {function.CSharpName}Request {{ /* params */ }},");
        WriteLine("timeout,");
        WriteLine("cancellationToken).ConfigureAwait(false);");
        DecreaseIndent();
        WriteLine(");");
        _output.AppendLine();
        WriteLine($"return response.{function.Name}Result;");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
    }
    
    private void GenerateServiceImplementation(ThriftService service)
    {
        var extendsFb303 = service.Extends != null 
            && service.Extends.Name == "BaseService" 
            && service.Extends.Namespace == "fb303";
        
        var baseInterface = extendsFb303 ? $"I{service.CSharpName}, IFb303BaseService" : $"I{service.CSharpName}";
        
        WriteLine($"public abstract class {service.CSharpName}Base : {baseInterface}");
        WriteLine("{");
        IncreaseIndent();
        
        foreach (var function in service.Functions)
        {
            WriteLine($"public abstract {GetReturnType(function)} {function.CSharpName}({GetParams(function)});");
        }
        
        // Add fb303 abstract methods if service extends fb303.BaseService
        if (extendsFb303)
        {
            _output.AppendLine();
            WriteLine($"/// <summary>fb303.BaseService methods</summary>");
            WriteLine($"public abstract Task<string> GetNameAsync(CancellationToken cancellationToken = default);");
            WriteLine($"public abstract Task<string> GetVersionAsync(CancellationToken cancellationToken = default);");
            WriteLine($"public abstract Task<ServiceStatus> GetStatusAsync(CancellationToken cancellationToken = default);");
            WriteLine($"public abstract Task<string> GetStatusDetailsAsync(CancellationToken cancellationToken = default);");
            WriteLine($"public abstract Task<Dictionary<string, string>> GetCountersAsync(CancellationToken cancellationToken = default);");
            WriteLine($"public abstract Task<Dictionary<string, string>> GetDynamicCountersAsync(CancellationToken cancellationToken = default);");
            WriteLine($"public abstract Task ReinitializeAsync(CancellationToken cancellationToken = default);");
        }
        
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
    }
    
    private void GenerateStructConstructor(ThriftStruct structType)
    {
        if (!structType.Fields.Any()) return;
        
        WriteLine($"public {structType.CSharpName}() {{ }}");
        _output.AppendLine();
        
        if (structType.Fields.Any(f => f.Required))
        {
            var requiredParams = structType.Fields.Where(f => f.Required).Select(f => $"{f.Type.CSharpName} {f.CSharpName}");
            WriteLine($"public {structType.CSharpName}({string.Join(", ", requiredParams)})");
            WriteLine("{");
            IncreaseIndent();
            foreach (var field in structType.Fields.Where(f => f.Required))
            {
                WriteLine($"{field.CSharpName} = {field.CSharpName};");
            }
            DecreaseIndent();
            WriteLine("}");
            _output.AppendLine();
        }
    }
    
    private void GenerateSerializationMethods(ThriftStruct structType)
    {
        // Write method
        WriteLine($"public void Write(TProtocolWriter writer)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"writer.WriteStructBegin(\"{structType.Name}\");");
        foreach (var field in structType.Fields)
        {
            WriteLine($"writer.WriteFieldBegin(\"{field.Name}\", TType.{field.Type.ThriftName.ToUpper()}, {field.Id});");
            WriteLine($"{GetWriteCall(field.Type, field.CSharpName)};");
            WriteLine("writer.WriteFieldEnd();");
        }
        WriteLine("writer.WriteFieldStop();");
        WriteLine("writer.WriteStructEnd();");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
        
        // Read method
        WriteLine($"public static {structType.CSharpName} Read(TProtocolReader reader)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"reader.ReadStructBegin(out _);");
        WriteLine($"var result = new {structType.CSharpName}();");
        _output.AppendLine();
        WriteLine("while (true)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine("reader.ReadFieldBegin(out _, out var fieldType, out var fieldId);");
        WriteLine("if (fieldType == TType.Stop) break;");
        WriteLine("switch (fieldId)");
        WriteLine("{");
        IncreaseIndent();
        foreach (var field in structType.Fields)
        {
            WriteLine($"case {field.Id}:");
            IncreaseIndent();
            WriteLine($"result.{field.CSharpName} = {GetReadCall(field.Type)};");
            WriteLine("break;");
            DecreaseIndent();
        }
        WriteLine("default:");
        IncreaseIndent();
        WriteLine("reader.Skip(fieldType);");
        WriteLine("break;");
        DecreaseIndent();
        DecreaseIndent();
        WriteLine("}");
        WriteLine("reader.ReadFieldEnd();");
        DecreaseIndent();
        WriteLine("}");
        WriteLine("reader.ReadStructEnd();");
        WriteLine("return result;");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
    }
    
    private void GenerateEqualityMethods(ThriftStruct structType)
    {
        if (!structType.Fields.Any()) return;
        
        WriteLine("public override bool Equals(object? obj)");
        WriteLine("{");
        IncreaseIndent();
        WriteLine($"return obj is {structType.CSharpName} other && Equals(other);");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
        
        WriteLine($"public bool Equals({structType.CSharpName}? other)");
        WriteLine("{");
        IncreaseIndent();
        if (structType.Fields.Count == 1)
        {
            var field = structType.Fields[0];
            WriteLine($"return other != null && {field.CSharpName}.Equals(other.{field.CSharpName});");
        }
        else
        {
            WriteLine("if (other == null) return false;");
            var conditions = structType.Fields.Select(f => f.CSharpName).Select(n => $"{n}.Equals(other.{n})");
            WriteLine($"return {string.Join(" && ", conditions)};");
        }
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
        
        WriteLine("public override int GetHashCode()");
        WriteLine("{");
        IncreaseIndent();
        var hashFields = string.Join(" ", structType.Fields.Select(f => $"{f.CSharpName}.GetHashCode()"));
        WriteLine($"return HashCode.Combine({hashFields});");
        DecreaseIndent();
        WriteLine("}");
        _output.AppendLine();
    }
    
    private void WriteField(ThriftField field)
    {
        if (_options.GenerateDocComments)
        {
            WriteLine($"/// <summary>Field {field.Id}: {field.Name}</summary>");
        }
        
        string nullability = field.Optional || field.Type.IsNullable ? "?" : "";
        WriteLine($"public {field.Type.CSharpName}{nullability} {field.CSharpName} {{ get; set; }}");
    }
    
    private void GenerateEqualityMethods(ThriftUnion union)
    {
        // Similar to struct but for union
    }
    
    private string GetWriteCall(ThriftType type, string fieldName)
    {
        return type.Kind switch
        {
            ThriftTypeKind.Base => type.ThriftName switch
            {
                "bool" => $"writer.WriteBool({fieldName})",
                "byte" => $"writer.WriteByte({fieldName})",
                "i16" => $"writer.WriteI16({fieldName})",
                "i32" => $"writer.WriteI32({fieldName})",
                "i64" => $"writer.WriteI64({fieldName})",
                "double" => $"writer.WriteDouble({fieldName})",
                "string" => $"writer.WriteString({fieldName})",
                "binary" => $"writer.WriteBinary({fieldName})",
                _ => $"writer.Write{type.CSharpName}({fieldName})"
            },
            ThriftTypeKind.List => $"writer.WriteListBegin(TType.{type.ElementType!.ThriftName.ToUpper()}, {fieldName}.Count); foreach (var item in {fieldName}) {{ {GetWriteCall(type.ElementType, "item")}; }} writer.WriteListEnd();",
            ThriftTypeKind.Set => $"writer.WriteSetBegin(TType.{type.ElementType!.ThriftName.ToUpper()}, {fieldName}.Count); foreach (var item in {fieldName}) {{ {GetWriteCall(type.ElementType, "item")}; }} writer.WriteSetEnd();",
            ThriftTypeKind.Map => $"writer.WriteMapBegin(TType.{type.KeyType!.ThriftName.ToUpper()}, TType.{type.ValueType!.ThriftName.ToUpper()}, {fieldName}.Count); foreach (var kvp in {fieldName}) {{ writer.WriteMapBegin(...); {GetWriteCall(type.KeyType, "kvp.Key")}; {GetWriteCall(type.ValueType, "kvp.Value")}; writer.WriteMapEnd(); }} writer.WriteMapEnd();",
            _ => throw new NotSupportedException($"Type {type.Kind} not supported for writing")
        };
    }
    
    private string GetReadCall(ThriftType type)
    {
        return type.Kind switch
        {
            ThriftTypeKind.Base => type.ThriftName switch
            {
                "bool" => "reader.ReadBool()",
                "byte" => "reader.ReadByte()",
                "i16" => "reader.ReadI16()",
                "i32" => "reader.ReadI32()",
                "i64" => "reader.ReadI64()",
                "double" => "reader.ReadDouble()",
                "string" => "reader.ReadString()",
                "binary" => "reader.ReadBinary()",
                _ => $"reader.Read{type.CSharpName}()"
            },
            ThriftTypeKind.List => "reader.ReadListBegin(out var elemType, out var size); var list = new List<T>(); for (int i = 0; i < size; i++) { list.Add(reader.ReadT()); } reader.ReadListEnd(); return list;",
            ThriftTypeKind.Set => "reader.ReadSetBegin(out var elemType, out var size); var set = new HashSet<T>(); for (int i = 0; i < size; i++) { set.Add(reader.ReadT()); } reader.ReadSetEnd(); return set;",
            ThriftTypeKind.Map => "reader.ReadMapBegin(out var keyType, out var valType, out var size); var dict = new Dictionary<TKey, TVal>(); for (int i = 0; i < size; i++) { dict.Add(reader.ReadKey(), reader.ReadValue()); } reader.ReadMapEnd(); return dict;",
            _ => throw new NotSupportedException($"Type {type.Kind} not supported for reading")
        };
    }
    
    private string FormatConstantValue(object? value)
    {
        return value switch
        {
            string s => $"\"{s.Replace("\"", "\\\"")}\"",
            bool b => b ? "true" : "false",
            null => "null",
            _ => value.ToString() ?? "null"
        };
    }
    
    private string GetReturnType(ThriftFunction function)
    {
        if (function.ReturnType.Kind == ThriftTypeKind.Base && function.ReturnType.ThriftName == "void")
            return function.IsAsync ? "Task" : "void";
        
        var typeName = function.ReturnType.CSharpName;
        return function.IsAsync ? $"Task<{typeName}>" : typeName;
    }
    
    private string GetParams(ThriftFunction function)
    {
        return string.Join(", ", function.Parameters.Select(p => 
            $"{p.Type.CSharpName} {p.CSharpName}"));
    }
    
    private void WriteDocComment(string text)
    {
        if (_options.GenerateDocComments)
        {
            WriteLine($"/// <summary>{text}</summary>");
        }
    }
