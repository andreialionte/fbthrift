namespace FbThrift.Generator;

using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

/// <summary>
/// Source generator for Thrift IDL files.
/// Generates C# classes implementing IThriftSerializable from .thrift files.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ThriftSourceGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Find all .thrift files in the project
        var thriftFiles = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith(".thrift", StringComparison.OrdinalIgnoreCase));

        // Parse each .thrift file
        var parsedFiles = thriftFiles.Select((file, ct) => ParseThriftFile(file, ct));

        // Generate code for each parsed file
        var generatedSources = parsedFiles.Select((parsed, ct) => GenerateCode(parsed, ct));

        context.RegisterSourceOutput(generatedSources, (ctx, source) => ctx.AddSource(source.FileName, source.SourceText));
    }

    private static ParsedThriftFile ParseThriftFile(AdditionalText file, CancellationToken ct)
    {
        var text = file.GetText(ct)?.ToString() ?? "";
        var parser = new ThriftParser(text);
        return parser.Parse(file.Path);
    }

    private static (string FileName, SourceText SourceText) GenerateCode(ParsedThriftFile parsed, CancellationToken ct)
    {
        var sb = new StringBuilder();
        
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine($"// Generated from {parsed.FileName}");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using FBThrift;");
        sb.AppendLine("using FBThrift.Core;");
        sb.AppendLine("using FBThrift.Core.Rocket;");
        sb.AppendLine("using FBThrift.Core.Transport;");
        sb.AppendLine();
        
        if (!string.IsNullOrEmpty(parsed.Namespace))
        {
            sb.AppendLine($"namespace {parsed.Namespace};");
            sb.AppendLine();
        }

        // Generate structs
        foreach (var structDef in parsed.Structs)
        {
            GenerateStruct(sb, structDef);
            sb.AppendLine();
        }

        // Generate enums
        foreach (var enumDef in parsed.Enums)
        {
            GenerateEnum(sb, enumDef);
            sb.AppendLine();
        }

        // Generate unions
        foreach (var unionDef in parsed.Unions)
        {
            GenerateUnion(sb, unionDef);
            sb.AppendLine();
        }

        // Generate services
        foreach (var serviceDef in parsed.Services)
        {
            GenerateService(sb, serviceDef, parsed);
            sb.AppendLine();
        }

        var fileName = $"{parsed.Namespace?.Replace('.', '_') ?? "Generated"}_Thrift.g.cs";
        return (fileName, SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void GenerateStruct(StringBuilder sb, ThriftStructDef structDef)
    {
        sb.AppendLine($"public sealed class {structDef.Name} : IThriftSerializable");
        sb.AppendLine("{");

        // Fields
        foreach (var field in structDef.Fields)
        {
            var csType = GetCSharpType(field.Type);
            var nullable = field.Required != ThriftFieldRequired.Required ? "?" : "";
            sb.AppendLine($"    public {csType}{nullable} {field.Name} {{ get; set; }}");
        }

        sb.AppendLine();

        // Clear
        sb.AppendLine("    public void __fbthrift_clear()");
        sb.AppendLine("    {");
        foreach (var field in structDef.Fields)
        {
            var csType = GetCSharpType(field.Type);
            if (IsNullableType(field.Type))
            {
                sb.AppendLine($"        {field.Name} = default;");
            }
            else
            {
                var defaultValue = GetDefaultValue(field.Type);
                sb.AppendLine($"        {field.Name} = {defaultValue};");
            }
        }
        sb.AppendLine("    }");

        sb.AppendLine();

        // IsEmpty
        sb.AppendLine("    public bool __fbthrift_is_empty()");
        sb.AppendLine("    {");
        if (structDef.Fields.Count == 0)
        {
            sb.AppendLine("        return true;");
        }
        else
        {
            var conditions = structDef.Fields
                .Where(f => f.Required == ThriftFieldRequired.Required)
                .Select(f => $"!EqualityComparer<{GetCSharpType(f.Type)}>.Default.Equals({f.Name}, default)");
            
            if (conditions.Any())
            {
                sb.AppendLine($"        return !({string.Join(" || ", conditions)});");
            }
            else
            {
                sb.AppendLine("        return true;");
            }
        }
        sb.AppendLine("    }");

        sb.AppendLine();

        // Write
        sb.AppendLine("    public void __fbthrift_write(IThriftProtocolWriter writer)");
        sb.AppendLine("    {");
        foreach (var field in structDef.Fields)
        {
            var wireType = GetWireType(field.Type);
            sb.AppendLine($"        writer.WriteFieldBegin({wireType}, {field.Id});");
            sb.AppendLine($"        writer.Write{GetWriteMethod(field.Type)}({field.Name});");
        }
        sb.AppendLine("        writer.WriteFieldStop();");
        sb.AppendLine("    }");

        sb.AppendLine();

        // Read
        sb.AppendLine("    public void __fbthrift_read(IThriftProtocolReader reader)");
        sb.AppendLine("    {");
        sb.AppendLine("        while (true)");
        sb.AppendLine("        {");
        sb.AppendLine("            var (fieldType, fieldId) = reader.ReadFieldBegin();");
        sb.AppendLine("            if (fieldType == ThriftWireType.Stop) break;");
        sb.AppendLine();

        foreach (var field in structDef.Fields)
        {
            sb.AppendLine($"            if (fieldId == {field.Id} && fieldType == {GetWireType(field.Type)})");
            sb.AppendLine("            {");
            sb.AppendLine($"                {field.Name} = reader.Read{GetReadMethod(field.Type)}();");
            sb.AppendLine("            }");
            sb.AppendLine("            else");
            sb.AppendLine("            {");
            sb.AppendLine("                reader.Skip(fieldType);");
            sb.AppendLine("            }");
        }

        sb.AppendLine("            reader.ReadFieldEnd();");
        sb.AppendLine("        }");
        sb.AppendLine("    }");

        sb.AppendLine();

        // Equality
        sb.AppendLine("    public override bool Equals(object? obj)");
        sb.AppendLine("    {");
        sb.AppendLine($"        return obj is {structDef.Name} other && Equals(other);");
        sb.AppendLine("    }");

        sb.AppendLine($"    public bool Equals({structDef.Name}? other)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (other is null) return false;");
        sb.AppendLine("        if (ReferenceEquals(this, other)) return true;");
        
        foreach (var field in structDef.Fields)
        {
            sb.AppendLine($"        if (!EqualityComparer<{GetCSharpType(field.Type)}>.Default.Equals({field.Name}, other.{field.Name})) return false;");
        }
        
        sb.AppendLine("        return true;");
        sb.AppendLine("    }");

        sb.AppendLine();

        sb.AppendLine("    public override int GetHashCode()");
        sb.AppendLine("    {");
        var hashFields = structDef.Fields.Select(f => f.Name).ToArray();
        if (hashFields.Length > 0)
        {
            sb.AppendLine($"        return HashCode.Combine({string.Join(", ", hashFields)});");
        }
        else
        {
            sb.AppendLine("        return 0;");
        }
        sb.AppendLine("    }");

        sb.AppendLine();

        sb.AppendLine("    public override string ToString()");
        sb.AppendLine("    {");
        var toStringParts = structDef.Fields.Select(f => $"\"{f.Name}={{ {f.Name} }}\"");
        sb.AppendLine($"        return $\"{structDef.Name} {{ {string.Join(", ", toStringParts)} }}\";");
        sb.AppendLine("    }");

        sb.AppendLine("}");
    }

    private static void GenerateEnum(StringBuilder sb, ThriftEnumDef enumDef)
    {
        sb.AppendLine($"public enum {enumDef.Name}");
        sb.AppendLine("{");
        foreach (var value in enumDef.Values)
        {
            sb.AppendLine($"    {value.Name} = {value.Value},");
        }
        sb.AppendLine("}");
    }

    private static void GenerateUnion(StringBuilder sb, ThriftUnionDef unionDef)
    {
        sb.AppendLine($"public sealed class {unionDef.Name} : ThriftUnion");
        sb.AppendLine("{");

        // Only one field can be set
        foreach (var field in unionDef.Fields)
        {
            var csType = GetCSharpType(field.Type);
            sb.AppendLine($"    public {csType}? {field.Name} {{ get; set; }}");
        }

        sb.AppendLine();

        // Clear
        sb.AppendLine("    public override void __fbthrift_clear()");
        sb.AppendLine("    {");
        foreach (var field in unionDef.Fields)
        {
            sb.AppendLine($"        {field.Name} = default;");
        }
        sb.AppendLine("    }");

        sb.AppendLine();

        // IsEmpty
        sb.AppendLine("    public override bool __fbthrift_is_empty()");
        sb.AppendLine("    {");
        var nullChecks = string.Join(" && ", unionDef.Fields.Select(f => $"{f.Name} == null"));
        sb.AppendLine($"        return {nullChecks};");
        sb.AppendLine("    }");

        sb.AppendLine();

        // Write
        sb.AppendLine("    public override void __fbthrift_write(IThriftProtocolWriter writer)");
        sb.AppendLine("    {");
        foreach (var field in unionDef.Fields)
        {
            var wireType = GetWireType(field.Type);
            sb.AppendLine($"        if ({field.Name} != null)");
            sb.AppendLine("        {");
            sb.AppendLine($"            writer.WriteFieldBegin({GetWireType(field.Type)}, {field.Id});");
            sb.AppendLine($"            writer.Write{GetWriteMethod(field.Type)}({field.Name}!);");
            sb.AppendLine("        }");
        }
        sb.AppendLine("        writer.WriteFieldStop();");
        sb.AppendLine("    }");

        sb.AppendLine();

        // Read
        sb.AppendLine("    public override void __fbthrift_read(IThriftProtocolReader reader)");
        sb.AppendLine("    {");
        sb.AppendLine("        while (true)");
        sb.AppendLine("        {");
        sb.AppendLine("            var (fieldType, fieldId) = reader.ReadFieldBegin();");
        sb.AppendLine("            if (fieldType == ThriftWireType.Stop) break;");
        sb.AppendLine();

        foreach (var field in unionDef.Fields)
        {
            sb.AppendLine($"            if (fieldId == {field.Id} && fieldType == {GetWireType(field.Type)})");
            sb.AppendLine("            {");
            sb.AppendLine($"    {field.Name} = reader.Read{GetReadMethod(field.Type)}();");
            sb.AppendLine("            }");
            sb.AppendLine("            else");
            sb.AppendLine("            {");
            sb.AppendLine("                reader.Skip(fieldType);");
            sb.AppendLine("            }");
        }

        sb.AppendLine("            reader.ReadFieldEnd();");
        sb.AppendLine("        }");
        sb.AppendLine("    }");

        sb.AppendLine("}");
    }

    private static void GenerateService(StringBuilder sb, ThriftServiceDef serviceDef, ParsedThriftFile parsed)
    {
        var serviceName = serviceDef.Name;
        var baseService = serviceDef.Extends;

        // Generate service interface
        GenerateServiceInterface(sb, serviceDef);

        // Generate client
        GenerateClient(sb, serviceDef, parsed);

        // Generate server base
        GenerateServer(sb, serviceDef, parsed);

        // Generate processor
        GenerateProcessor(sb, serviceDef, parsed);
    }

    private static void GenerateServiceInterface(StringBuilder sb, ThriftServiceDef serviceDef)
    {
        sb.AppendLine($"public interface I{serviceDef.Name}");
        if (!string.IsNullOrEmpty(serviceDef.Extends))
        {
            sb.AppendLine($"    : I{serviceDef.Extends}");
        }
        sb.AppendLine("{");

        foreach (var method in serviceDef.Methods)
        {
            var returnType = GetCSharpType(method.ReturnType);
            var isVoid = method.ReturnType == ThriftType.Void;
            
            // Check if method is oneway (fire-and-forget)
            var isOneway = method.Annotations.ContainsKey("oneway");
            
            if (isOneway)
            {
                sb.AppendLine($"    Task {method.Name}({GenerateMethodParams(method)});");
            }
            else
            {
                sb.AppendLine($"    Task<{returnType}> {method.Name}({GenerateMethodParams(method)});");
            }
        }

        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void GenerateClient(StringBuilder sb, ThriftServiceDef serviceDef, ParsedThriftFile parsed)
    {
        var clientName = $"{serviceDef.Name}Client";
        
        sb.AppendLine($"public sealed class {clientName} : I{serviceDef.Name}, IAsyncDisposable");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly RocketClient _rocketClient;");
        sb.AppendLine("    private readonly RpcOptions _options;");
        sb.AppendLine();
        sb.AppendLine($"    public {clientName}(IFbThriftTransport transport, RpcOptions? options = null)");
        sb.AppendLine("    {");
        sb.AppendLine("        _rocketClient = new RocketClient(transport as RocketTransport ?? throw new ArgumentException(\"Transport must be RocketTransport\"), options);");
        sb.AppendLine("        _options = options ?? new RpcOptions();");
        sb.AppendLine("    }");
        sb.AppendLine();

        foreach (var method in serviceDef.Methods)
        {
            var returnType = GetCSharpType(method.ReturnType);
            var isVoid = method.ReturnType == ThriftType.Void;
            var isOneway = method.Annotations.ContainsKey("oneway");

            if (isOneway)
            {
                sb.AppendLine($"    public async Task {method.Name}({GenerateMethodParams(method)})");
                sb.AppendLine("    {");
                sb.AppendLine($"        var request = new {serviceDef.Name}_{method.Name}_Args {{");
                foreach (var param in method.Parameters)
                {
                    sb.AppendLine($"            {param.Name} = {param.Name},");
                }
                sb.AppendLine("        };");
                sb.AppendLine($"        await _rocketClient.CallAsync<{serviceDef.Name}_{method.Name}_Args, ThriftVoid>(\"{method.Name}\", request, _options).ConfigureAwait(false);");
                sb.AppendLine("    }");
                sb.AppendLine();
            }
            else
            {
                sb.AppendLine($"    public async Task<{returnType}> {method.Name}({GenerateMethodParams(method)})");
                sb.AppendLine("    {");
                sb.AppendLine($"        var request = new {serviceDef.Name}_{method.Name}_Args {{");
                foreach (var param in method.Parameters)
                {
                    sb.AppendLine($"            {param.Name} = {param.Name},");
                }
                sb.AppendLine("        };");
                sb.AppendLine($"        var response = await _rocketClient.CallAsync<{serviceDef.Name}_{method.Name}_Args, {serviceDef.Name}_{method.Name}_Result>(\"{method.Name}\", request, _options).ConfigureAwait(false);");
                
                if (method.ReturnType != ThriftType.Void)
                {
                    sb.AppendLine($"        return response.{method.Name};");
                }
                else
                {
                    sb.AppendLine("        return default!;");
                }
                sb.AppendLine("    }");
                sb.AppendLine();
            }
        }

        sb.AppendLine("    public async ValueTask DisposeAsync()");
        sb.AppendLine("    {");
        sb.AppendLine("        await _rocketClient.DisposeAsync().ConfigureAwait(false);");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();

        // Generate Args struct
        foreach (var method in serviceDef.Methods)
        {
            GenerateArgsStruct(sb, serviceDef, method);
        }

        // Generate Result struct
        foreach (var method in serviceDef.Methods)
        {
            GenerateResultStruct(sb, serviceDef, method);
        }
    }

    private static void GenerateServer(StringBuilder sb, ThriftServiceDef serviceDef, ParsedThriftFile parsed)
    {
        var serverName = $"{serviceDef.Name}Server";
        
        sb.AppendLine($"public abstract class {serverName} : I{serviceDef.Name}");
        sb.AppendLine("{");
        
        foreach (var method in serviceDef.Methods)
        {
            var returnType = GetCSharpType(method.ReturnType);
            var isVoid = method.ReturnType == ThriftType.Void;
            var isOneway = method.Annotations.ContainsKey("oneway");

            if (isOneway)
            {
                sb.AppendLine($"    public abstract Task {method.Name}({GenerateMethodParams(method)});");
            }
            else
            {
                sb.AppendLine($"    public abstract Task<{returnType}> {method.Name}({GenerateMethodParams(method)});");
            }
        }

        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void GenerateProcessor(StringBuilder sb, ThriftServiceDef serviceDef, ParsedThriftFile parsed)
    {
        var processorName = $"{serviceDef.Name}Processor";
        
        sb.AppendLine($"public sealed class {processorName} : IThriftProcessor");
        sb.AppendLine("{");
        sb.AppendLine($"    private readonly {serviceDef.Name}Server _handler;");
        sb.AppendLine();
        sb.AppendLine($"    public {processorName}({serviceDef.Name}Server handler)");
        sb.AppendLine("    {");
        sb.AppendLine("        _handler = handler ?? throw new ArgumentNullException(nameof(handler));");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public async Task<bool> ProcessAsync(ReadOnlyMemory<byte> input, Memory<byte> output, CancellationToken cancellationToken = default)");
        sb.AppendLine("    {");
        sb.AppendLine("        // Parse Rocket frame");
        sb.AppendLine("        var reader = new CompactProtocolReader(input);");
        sb.AppendLine("        var (methodName, _, _) = reader.ReadMessageBegin();");
        sb.AppendLine("        reader.ReadStructBegin();");
        sb.AppendLine();
        sb.AppendLine("        switch (methodName)");
        sb.AppendLine("        {");

        foreach (var method in serviceDef.Methods)
        {
            var returnType = GetCSharpType(method.ReturnType);
            var isVoid = method.ReturnType == ThriftType.Void;
            var isOneway = method.Annotations.ContainsKey("oneway");

            sb.AppendLine($"            case \"{method.Name}\":");
            sb.AppendLine("                {");
            sb.AppendLine($"                    var args = new {serviceDef.Name}_{method.Name}_Args();");
            sb.AppendLine("                    args.__fbthrift_read(reader);");
            sb.AppendLine("                    reader.ReadStructEnd();");
            sb.AppendLine("                    reader.ReadMessageEnd();");
            sb.AppendLine();
            
            if (isOneway)
            {
                sb.AppendLine($"                    await _handler.{method.Name}(");
                sb.AppendLine(string.Join(",\n", method.Parameters.Select(p => $"                        args.{p.Name}")));
                sb.AppendLine("                    ).ConfigureAwait(false);");
                sb.AppendLine();
                sb.AppendLine("                    // Oneway - no response");
                sb.AppendLine("                    return false;");
            }
            else
            {
                sb.AppendLine($"                    var result = await _handler.{method.Name}(");
                sb.AppendLine(string.Join(",\n", method.Parameters.Select(p => $"                        args.{p.Name}")));
                sb.AppendLine("                    ).ConfigureAwait(false);");
                sb.AppendLine();
                sb.AppendLine($"                    var response = new {serviceDef.Name}_{method.Name}_Result {{ {method.Name} = result }};");
                sb.AppendLine();
                sb.AppendLine("                    var writer = new CompactProtocolWriter(output);");
                sb.AppendLine($"                    writer.WriteMessageBegin(\"{method.Name}\", TMessageType.Reply, 0);");
                sb.AppendLine("                    response.__fbthrift_write(writer);");
                sb.AppendLine("                    writer.WriteMessageEnd();");
                sb.AppendLine("                    return true;");
            }
            sb.AppendLine("                }");
        }

        sb.AppendLine("            default:");
        sb.AppendLine("                return false;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void GenerateArgsStruct(StringBuilder sb, ThriftServiceDef serviceDef, ThriftMethodDef method)
    {
        var structName = $"{serviceDef.Name}_{method.Name}_Args";
        
        sb.AppendLine($"public sealed class {structName} : IThriftSerializable");
        sb.AppendLine("{");

        foreach (var param in method.Parameters)
        {
            var csType = GetCSharpType(param.Type);
            var nullable = IsNullableType(param.Type) ? "?" : "";
            sb.AppendLine($"    public {csType}{nullable} {param.Name} {{ get; set; }}");
        }

        sb.AppendLine();
        sb.AppendLine("    public void __fbthrift_clear()");
        sb.AppendLine("    {");
        foreach (var param in method.Parameters)
        {
            if (IsNullableType(param.Type))
            {
                sb.AppendLine($"        {param.Name} = default;");
            }
            else
            {
                sb.AppendLine($"        {param.Name} = {GetDefaultValue(param.Type)};");
            }
        }
        sb.AppendLine("    }");

        sb.AppendLine();
        sb.AppendLine("    public bool __fbthrift_is_empty() => false;");
        sb.AppendLine();

        sb.AppendLine("    public void __fbthrift_write(IThriftProtocolWriter writer)");
        sb.AppendLine("    {");
        foreach (var param in method.Parameters)
        {
            var wireType = GetWireType(param.Type);
            sb.AppendLine($"        writer.WriteFieldBegin({wireType}, {param.Id});");
            sb.AppendLine($"        writer.Write{GetWriteMethod(param.Type)}({param.Name});");
        }
        sb.AppendLine("        writer.WriteFieldStop();");
        sb.AppendLine("    }");

        sb.AppendLine();
        sb.AppendLine("    public void __fbthrift_read(IThriftProtocolReader reader)");
        sb.AppendLine("    {");
        sb.AppendLine("        while (true)");
        sb.AppendLine("        {");
        sb.AppendLine("            var (fieldType, fieldId) = reader.ReadFieldBegin();");
        sb.AppendLine("            if (fieldType == ThriftWireType.Stop) break;");
        sb.AppendLine();

        foreach (var param in method.Parameters)
        {
            sb.AppendLine($"            if (fieldId == {param.Id} && fieldType == {GetWireType(param.Type)})");
            sb.AppendLine("            {");
            sb.AppendLine($"                {param.Name} = reader.Read{GetReadMethod(param.Type)}();");
            sb.AppendLine("            }");
            sb.AppendLine("            else");
            sb.AppendLine("            {");
            sb.AppendLine("                reader.Skip(fieldType);");
            sb.AppendLine("            }");
        }

        sb.AppendLine("            reader.ReadFieldEnd();");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void GenerateResultStruct(StringBuilder sb, ThriftServiceDef serviceDef, ThriftMethodDef method)
    {
        var structName = $"{serviceDef.Name}_{method.Name}_Result";
        
        sb.AppendLine($"public sealed class {structName} : IThriftSerializable");
        sb.AppendLine("{");

        var returnType = GetCSharpType(method.ReturnType);
        var isVoid = method.ReturnType == ThriftType.Void;
        var nullable = !isVoid && IsNullableType(method.ReturnType) ? "?" : "";

        if (!isVoid)
        {
            sb.AppendLine($"    public {returnType}{nullable} {method.Name} {{ get; set; }}");
        }

        sb.AppendLine();
        sb.AppendLine("    public void __fbthrift_clear()");
        sb.AppendLine("    {");
        if (!isVoid)
        {
            if (IsNullableType(method.ReturnType))
            {
                sb.AppendLine($"        {method.Name} = default;");
            }
            else
            {
                sb.AppendLine($"        {method.Name} = {GetDefaultValue(method.ReturnType)};");
            }
        }
        sb.AppendLine("    }");

        sb.AppendLine();
        sb.AppendLine("    public bool __fbthrift_is_empty() => false;");
        sb.AppendLine();

        sb.AppendLine("    public void __fbthrift_write(IThriftProtocolWriter writer)");
        sb.AppendLine("    {");
        if (!isVoid)
        {
            var wireType = GetWireType(method.ReturnType);
            sb.AppendLine($"        writer.WriteFieldBegin({wireType}, 0);");
            sb.AppendLine($"        writer.Write{GetWriteMethod(method.ReturnType)}({method.Name});");
        }
        sb.AppendLine("        writer.WriteFieldStop();");
        sb.AppendLine("    }");

        sb.AppendLine();
        sb.AppendLine("    public void __fbthrift_read(IThriftProtocolReader reader)");
        sb.AppendLine("    {");
        sb.AppendLine("        while (true)");
        sb.AppendLine("        {");
        sb.AppendLine("            var (fieldType, fieldId) = reader.ReadFieldBegin();");
        sb.AppendLine("            if (fieldType == ThriftWireType.Stop) break;");
        sb.AppendLine();

        if (!isVoid)
        {
            sb.AppendLine($"            if (fieldId == 0 && fieldType == {GetWireType(method.ReturnType)})");
            sb.AppendLine("            {");
            sb.AppendLine($"                {method.Name} = reader.Read{GetReadMethod(method.ReturnType)}();");
            sb.AppendLine("            }");
            sb.AppendLine("            else");
            sb.AppendLine("            {");
            sb.AppendLine("                reader.Skip(fieldType);");
            sb.AppendLine("            }");
        }
        else
        {
            sb.AppendLine("            reader.Skip(fieldType);");
        }

        sb.AppendLine("            reader.ReadFieldEnd();");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static string GenerateMethodParams(ThriftMethodDef method)
    {
        return string.Join(", ", method.Parameters.Select(p => 
        {
            var csType = GetCSharpType(p.Type);
            var nullable = IsNullableType(p.Type) ? "?" : "";
            return $"{csType}{nullable} {p.Name}";
        }));
    }

