    String,
    Binary,
    List,
    Set,
    Map,
    Struct,
    Enum,
    Void
}

/// <summary>
/// Simple Thrift IDL parser.
/// </summary>
public sealed class ThriftParser
{
    private readonly string _text;
    private int _pos;

    public ThriftParser(string text)
    {
        _text = text;
    }

    public ParsedThriftFile Parse(string fileName)
    {
        var result = new ParsedThriftFile { FileName = fileName };
        
        while (_pos < _text.Length)
        {
            SkipWhitespaceAndComments();
            if (_pos >= _text.Length) break;

            if (MatchKeyword("namespace"))
            {
                SkipWhitespaceAndComments();
                MatchKeyword("csharp");
                SkipWhitespaceAndComments();
                result.Namespace = ParseIdentifier();
            }
            else if (MatchKeyword("struct"))
            {
                result.Structs.Add(ParseStruct());
            }
            else if (MatchKeyword("enum"))
            {
                result.Enums.Add(ParseEnum());
            }
            else if (MatchKeyword("union"))
            {
                result.Unions.Add(ParseUnion());
            }
            else if (MatchKeyword("service"))
            {
                result.Services.Add(ParseService());
            }
            else if (MatchKeyword("typedef") || MatchKeyword("const") || MatchKeyword("exception"))
            {
                // Skip for now
                SkipToNextStatement();
            }
            else
            {
                _pos++;
            }
        }

        return result;
    }

    private ThriftServiceDef ParseService()
    {
        var serviceName = ParseIdentifier();
        var service = new ThriftServiceDef { Name = serviceName };

        SkipWhitespaceAndComments();
        if (MatchKeyword("extends"))
        {
            SkipWhitespaceAndComments();
            service.Extends = ParseIdentifier();
        }

        Expect('{');

        while (!Match('}') && _pos < _text.Length)
        {
            SkipWhitespaceAndComments();
            if (_pos >= _text.Length) break;

            if (MatchKeyword("oneway"))
            {
                // Oneway method
                var method = ParseMethod();
                method.Annotations["oneway"] = "true";
                service.Methods.Add(method);
            }
            else
            {
                var method = ParseMethod();
                service.Methods.Add(method);
            }
        }

        return service;
    }

    private ThriftMethodDef ParseMethod()
    {
        var method = new ThriftMethodDef();

        SkipWhitespaceAndComments();
        var returnType = ParseType();
        method.ReturnType = returnType;

        SkipWhitespaceAndComments();
        method.Name = ParseIdentifier();

        Expect('(');
        
        // Parse parameters
        SkipWhitespaceAndComments();
        if (!Match(')'))
        {
            while (true)
            {
                SkipWhitespaceAndComments();
                
                var paramId = int.Parse(ParseNumber());
                SkipWhitespaceAndComments();
                
                var required = ThriftFieldRequired.Optional;
                if (MatchKeyword("required")) required = ThriftFieldRequired.Required;
                else if (MatchKeyword("optional")) required = ThriftFieldRequired.Optional;

                SkipWhitespaceAndComments();
                var paramType = ParseType();
                SkipWhitespaceAndComments();
                var paramName = ParseIdentifier();
                
                var param = new ThriftFieldDef { Id = paramId, Name = paramName, Type = paramType, Required = required };
                method.Parameters.Add(param);

                SkipWhitespaceAndComments();
                if (Match(')')) break;
                Match(',');
            }
        }

        // Skip throws clause if present
        SkipWhitespaceAndComments();
        if (MatchKeyword("throws"))
        {
            SkipToNextStatement();
        }

        Match(';');

        return method;
    }

    private ThriftStructDef ParseStruct()
    {
        var structName = ParseIdentifier();
        Expect('{');
        var fields = new List<ThriftFieldDef>();

        while (!Match('}') && _pos < _text.Length)
        {
            SkipWhitespaceAndComments();
            if (_pos >= _text.Length) break;

            var field = ParseField();
            if (field != null) fields.Add(field);
        }

        return new ThriftStructDef { Name = structName, Fields = fields };
    }

    private ThriftFieldDef? ParseField()
    {
        SkipWhitespaceAndComments();
        
        if (!int.TryParse(ParseNumber(), out int id))
            return null;

        SkipWhitespaceAndComments();
        
        var required = ThriftFieldRequired.Optional;
        if (MatchKeyword("required")) required = ThriftFieldRequired.Required;
        else if (MatchKeyword("optional")) required = ThriftFieldRequired.Optional;

        SkipWhitespaceAndComments();
        var type = ParseType();
        SkipWhitespaceAndComments();
        var name = ParseIdentifier();
        SkipWhitespaceAndComments();

        string? defaultValue = null;
        if (Match('='))
        {
            SkipWhitespaceAndComments();
            defaultValue = ParseValue();
        }

        Match(',');
        Match(';');

        return new ThriftFieldDef { Id = id, Name = name, Type = type, Required = required, DefaultValue = defaultValue };
    }

    private ThriftType ParseType()
    {
        var identifier = ParseIdentifier().ToLowerInvariant();
        return identifier switch
        {
            "bool" => ThriftType.Bool,
            "byte" or "i8" => ThriftType.Byte,
            "i16" => ThriftType.I16,
            "i32" => ThriftType.I32,
            "i64" => ThriftType.I64,
            "double" => ThriftType.Double,
            "float" => ThriftType.Float,
            "string" => ThriftType.String,
            "binary" => ThriftType.Binary,
            "void" => ThriftType.Void,
            _ when identifier.StartsWith("list<") => ThriftType.List,
            _ when identifier.StartsWith("set<") => ThriftType.Set,
            _ when identifier.StartsWith("map<") => ThriftType.Map,
            _ => ThriftType.Struct
        };
    }

    private ThriftEnumDef ParseEnum()
    {
        var enumName = ParseIdentifier();
        Expect('{');
        var values = new List<ThriftEnumValue>();
        int currentValue = 0;

        while (!Match('}') && _pos < _text.Length)
        {
            SkipWhitespaceAndComments();
            if (_pos >= _text.Length) break;

            var valueName = ParseIdentifier();
            int enumValue = currentValue;
            if (Match('='))
            {
                SkipWhitespaceAndComments();
                int.TryParse(ParseNumber(), out enumValue);
            }
            currentValue = enumValue + 1;

            values.Add(new ThriftEnumValue { Name = valueName, Value = enumValue });
            Match(',');
        }

        return new ThriftEnumDef { Name = enumName, Values = values };
    }

    private ThriftUnionDef ParseUnion()
    {
        var unionName = ParseIdentifier();
        Expect('{');
        var fields = new List<ThriftFieldDef>();

        while (!Match('}') && _pos < _text.Length)
        {
            SkipWhitespaceAndComments();
            if (_pos >= _text.Length) break;

            var field = ParseField();
            if (field != null) fields.Add(field);
        }

        return new ThriftUnionDef { Name = unionName, Fields = fields };
    }

    private void SkipWhitespaceAndComments()
    {
        while (_pos < _text.Length)
        {
            if (char.IsWhiteSpace(_text[_pos]))
            {
                _pos++;
            }
            else if (_pos + 1 < _text.Length && _text[_pos] == '/' && _text[_pos + 1] == '/')
            {
                _pos += 2;
                while (_pos < _text.Length && _text[_pos] != '\n') _pos++;
            }
            else if (_pos + 1 < _text.Length && _text[_pos] == '/' && _text[_pos + 1] == '*')
            {
                _pos += 2;
                while (_pos + 1 < _text.Length && !(_text[_pos] == '*' && _text[_pos + 1] == '/')) _pos++;
                _pos += 2;
            }
            else break;
        }
    }

    private bool Match(char c)
    {
        SkipWhitespaceAndComments();
        if (_pos < _text.Length && _text[_pos] == c)
        {
            _pos++;
            return true;
        }
        return false;
    }

    private bool MatchKeyword(string keyword)
    {
        SkipWhitespaceAndComments();
        if (_pos + keyword.Length <= _text.Length && 
            _text.Substring(_pos, keyword.Length).Equals(keyword, StringComparison.OrdinalIgnoreCase))
        {
            var nextChar = _pos + keyword.Length < _text.Length ? _text[_pos + keyword.Length] : '\0';
            if (!char.IsLetterOrDigit(nextChar) && nextChar != '_')
            {
                _pos += keyword.Length;
                return true;
            }
        }
        return false;
    }

    private void Expect(char c)
    {
        SkipWhitespaceAndComments();
        if (_pos < _text.Length && _text[_pos] == c)
        {
            _pos++;
        }
    }

    private string ParseIdentifier()
    {
        SkipWhitespaceAndComments();
        var start = _pos;
        while (_pos < _text.Length && (char.IsLetterOrDigit(_text[_pos]) || _text[_pos] == '_' || _text[_pos] == '.'))
        {
            _pos++;
        }
        return _text.Substring(start, _pos - start);
    }

    private string ParseNumber()
    {
        SkipWhitespaceAndComments();
        var start = _pos;
        while (_pos < _text.Length && char.IsDigit(_text[_pos]))
        {
            _pos++;
        }
        return _text.Substring(start, _pos - start);
    }

    private string ParseValue()
    {
        SkipWhitespaceAndComments();
        var start = _pos;
        while (_pos < _text.Length && _text[_pos] != ',' && _text[_pos] != ';' && _text[_pos] != '}' && !char.IsWhiteSpace(_text[_pos]))
        {
            _pos++;
        }
        return _text.Substring(start, _pos - start).TrimEnd();
    }

    private void SkipToNextStatement()
    {
        while (_pos < _text.Length && _text[_pos] != ';' && _text[_pos] != '}')
        {
            _pos++;
        }
        if (_pos < _text.Length) _pos++;
    }
}