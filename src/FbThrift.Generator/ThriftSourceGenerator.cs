/// <summary>
/// Parsed Thrift file representation.
/// </summary>
public sealed class ParsedThriftFile
{
    public string FileName { get; set; } = "";
    public string Namespace { get; set; } = "";
    public List<ThriftStructDef> Structs { get; set; } = new();
    public List<ThriftEnumDef> Enums { get; set; } = new();
    public List<ThriftUnionDef> Unions { get; set; } = new();
    public List<ThriftServiceDef> Services { get; set; } = new();
}

/// <summary>
/// Thrift struct definition.
/// </summary>
public sealed class ThriftStructDef
{
    public string Name { get; set; } = "";
    public List<ThriftFieldDef> Fields { get; set; } = new();
}

/// <summary>
/// Thrift field definition.
/// </summary>
public sealed class ThriftFieldDef
{
    public int Id { get; set; }
    public string Name { get; set; } = "";
    public ThriftType Type { get; set; }
    public ThriftFieldRequired Required { get; set; } = ThriftFieldRequired.Optional;
    public string? DefaultValue { get; set; }
}

/// <summary>
/// Thrift enum definition.
/// </summary>
public sealed class ThriftEnumDef
{
    public string Name { get; set; } = "";
    public List<ThriftEnumValue> Values { get; set; } = new();
}

/// <summary>
/// Thrift enum value.
/// </summary>
public sealed class ThriftEnumValue
{
    public string Name { get; set; } = "";
    public int Value { get; set; }
}

/// <summary>
/// Thrift union definition.
/// </summary>
public sealed class ThriftUnionDef
{
    public string Name { get; set; } = "";
    public List<ThriftFieldDef> Fields { get; set; } = new();
}

/// <summary>
/// Thrift service definition.
/// </summary>
public sealed class ThriftServiceDef
{
    public string Name { get; set; } = "";
    public string Extends { get; set; } = "";
    public List<ThriftMethodDef> Methods { get; set; } = new();
}

/// <summary>
/// Thrift method definition.
/// </summary>
public sealed class ThriftMethodDef
{
    public string Name { get; set; } = "";
    public ThriftType ReturnType { get; set; }
    public List<ThriftFieldDef> Parameters { get; set; } = new();
    public Dictionary<string, string> Annotations { get; set; } = new();
}

/// <summary>
